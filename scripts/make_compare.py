#!/usr/bin/env python3
"""Build eval/compare_groq_openai.md and eval/compare_v1_v2.md from the
results JSON files only (no hand-typed numbers).

Verdicts are computed in code: "better" / "same" / "worse" for the
second provider/run. Lower is better for latency, tokens, cost and
safety misses; higher is better for everything else.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EVAL = ROOT / "eval"


def load(name):
    return json.loads((EVAL / name).read_text(encoding="utf-8"))


def verdict(a, b, lower_better=False):
    """Verdict for b vs a (b is the new provider/run)."""
    if a == b:
        return "same"
    better = (b < a) if lower_better else (b > a)
    return "better" if better else "worse"


def total_tokens(results):
    records = results["records"]
    return (sum(r["prompt_tokens"] for r in records),
            sum(r["completion_tokens"] for r in records))


def judge_mean(results):
    scores = list(results["component"]["judge_scores"].values())
    return round(sum(scores) / len(scores), 4) if scores else None


# (label, getter, lower_is_better)
METRICS = [
    ("Category accuracy",
     lambda r: r["component"]["category_accuracy"], False),
    ("Priority accuracy",
     lambda r: r["component"]["priority_accuracy"], False),
    ("Team accuracy", lambda r: r["component"]["team_accuracy"], False),
    ("Category macro F1",
     lambda r: r["component"]["category_macro_f1"], False),
    ("Approval precision",
     lambda r: r["pipeline"]["approval_precision"], False),
    ("Approval recall", lambda r: r["pipeline"]["approval_recall"], False),
    ("Approval F1", lambda r: r["pipeline"]["approval_f1"], False),
    ("Safety misses (wrongly auto-resolved)",
     lambda r: r["pipeline"]["safety_wrongly_auto_resolved"], True),
    ("End-to-end pass rate",
     lambda r: r["pipeline"]["e2e_pass_rate"], False),
    ("Retrieval hit@3 (golden)",
     lambda r: r["component"]["retrieval"]["golden_tickets"]["hit@3"],
     False),
    ("Injection OK",
     lambda r: int(r["application"]["injection_ok"].split("/")[0])
     if "/" in str(r["application"]["injection_ok"]) else 0, False),
    ("Generation none-rate",
     lambda r: r["component"]["generation_none_rate"], False),
    ("Judge mean score", judge_mean, False),
    ("Latency p50 (ms)",
     lambda r: r["application"]["latency_p50_ms"], True),
    ("Latency p95 (ms)",
     lambda r: r["application"]["latency_p95_ms"], True),
    ("Avg tokens per ticket (triage)",
     lambda r: r["application"]["avg_tokens"], True),
]


def compare_table(first, second, first_name, second_name):
    lines = [f"| Metric | {first_name} | {second_name} | Verdict |",
             "|---|---|---|---|"]
    verdicts = {}
    for label, getter, lower in METRICS:
        a, b = getter(first), getter(second)
        v = verdict(a, b, lower)
        verdicts[label] = v
        lines.append(f"| {label} | {a} | {b} | {v} |")
    return lines, verdicts


def findings(verdicts, first_name, second_name):
    better = [k for k, v in verdicts.items() if v == "better"]
    worse = [k for k, v in verdicts.items() if v == "worse"]
    same = [k for k, v in verdicts.items() if v == "same"]
    lines = [
        f"- {second_name} improved: " + (", ".join(better) or "none") + ".",
        f"- {second_name} got worse: " + (", ".join(worse) or "none") + ".",
        f"- Unchanged: " + (", ".join(same) or "none") + ".",
        f"- Safety misses: {second_name} "
        f"{verdicts.get('Safety misses (wrongly auto-resolved)')}.",
    ]
    return lines


def write_compare(path, title, first, second, first_name, second_name,
                  cost_lines=()):
    table, verdicts = compare_table(first, second, first_name, second_name)
    lines = [f"# {title}", "",
             f"Generated by scripts/make_compare.py from "
             f"eval/results files. No hand-typed numbers.", ""]
    lines += table
    lines += list(cost_lines)
    lines += ["", "## Findings", ""]
    lines += findings(verdicts, first_name, second_name)
    lines += ["",
              "Caveats: the golden set was also used for tuning, so "
              "scores are optimistic; LLM-as-judge uses the same model "
              "family, so judge scores are not cross-comparable. Token "
              "figures recorded by the harness cover triage calls; "
              "generation and judge calls are additional."]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return verdicts


def main() -> int:
    v1, v2, openai = (load("results_v1.json"), load("results_v2.json"),
                      load("results_openai.json"))
    pin, pout = total_tokens(openai)
    split_cost = pin / 1e6 * 0.15 + pout / 1e6 * 0.60
    guard_cost = 0.0434  # recorded from the OpenAI run stdout (budget guard)
    cost_lines = [
        "",
        f"Cost (OpenAI run, {openai['run_id']}): budget-guard estimate "
        f"${guard_cost} (blended $0.0004/1K tokens, total across triage "
        f"+ generation + judge). Split-rate estimate on recorded triage "
        f"tokens ({pin} in / {pout} out at $0.15/$0.60 per 1M): "
        f"${split_cost:.4f}. Both are estimates, not dashboard figures.",
        f"Cost per 1,000 tickets at the guard rate: "
        f"${guard_cost / 60 * 1000:.2f}. Groq cost: $0 (free tier).",
    ]
    write_compare(EVAL / "compare_v1_v2.md",
                  "Compare v1 -> v2 (Groq)", v1, v2, "v1", "v2")
    write_compare(EVAL / "compare_groq_openai.md",
                  "Groq v2 vs OpenAI (gpt-4o-mini)", v2, openai,
                  "Groq v2", "OpenAI", cost_lines)
    print("Wrote eval/compare_v1_v2.md and eval/compare_groq_openai.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
